def heat(ax, M, cmap, norm, fmt, title, xt, yt):
    ax.imshow(M, cmap=cmap, norm=norm, aspect="auto")
    for i in range(M.shape[0]):
        for j in range(M.shape[1]):
            v = M[i, j]
            if np.isnan(v):
                ax.text(j, i, "—", ha="center", va="center", fontsize=7, color=INK2)
            else:
                ax.text(j, i, fmt(v), ha="center", va="center", fontsize=7, color=INK)
    ax.set_xticks(range(len(xt)), xt, fontsize=7.5, rotation=40, ha="right")
    ax.set_yticks(range(len(yt)), yt, fontsize=8)
    ax.set_title(title, fontsize=9, color=INK)
    for s in ax.spines.values():
        s.set_visible(False)
    ax.tick_params(length=0, colors=INK2)


