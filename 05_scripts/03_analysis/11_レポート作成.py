def phrase_city(city):
    """「○○市の（分野）で、Aを伸ばし、Bを減らし」の部分。"""
    s = sel[sel["市"] == city]
    up = [k for k, sg in zip(s["表示名"], s["望ましい向き"]) if sg > 0]
    dn = [k for k, sg in zip(s["表示名"], s["望ましい向き"]) if sg < 0]
    parts = []
    if up:
        parts.append(("・".join(up), "伸ばし", "伸ばす"))
    if dn:
        parts.append(("・".join(dn), "減らし", "減らす"))
    return f"{city}の{focus[city]}で、", parts


def answer():
    out, cities = "", [MAIN, SUB]
    for n, c in enumerate(cities):
        head, parts = phrase_city(c)
        out += head
        for k, (txt, cont, end) in enumerate(parts):
            last = n == len(cities) - 1 and k == len(parts) - 1
            out += f"{txt}を" + (f"{end}べきである。" if last else f"{cont}、")
    return out


