"""ステップ7：目的への答え ― ターゲットの市ごとに、重点分野で「伸ばす数値」を決める。

重点分野の変数（個別KPI・追加の変数）のうち、次の4つをすべて満たすものを伸ばす数値にする。
  1. 主観スコアを説明できる：改善候補②の最終モデル（土台＋個別KPI＋追加の変数のElastic Net）で効いた
     （市町村単位のブートストラップで想定どおりの向きが90%以上）
  2. 施策で動かせる：操作可能性が「短期」または「中長期」（「困難」は対象外。common.CONTROL）
  3. 伸びしろがある：市の値が同じ類型の上位4分の1に届いていない（ステップ6）
  4. 年ごとの変化と食い違わない：因果の確認（ステップ5）で、主観スコアにも幸福度にも逆向きに有意でない
     （1時点しかない変数は確かめられないため、条件を満たすものとして扱い、その旨を記す）
見込み：
  主観スコアの上がり幅 ＝ 係数（1単位あたり、最終モデル）× 伸びしろ
  幸福度の上がり幅 ＝ 主観スコアの上がり幅 × 主観スコア1点あたりの幸福度（ステップ3、その市の類型のElastic Net）
  最終モデルは変数をまとめて入れた重回帰なので、複数の数値の上がり幅は足し合わせられる（変数同士の重なりは差し引き済み）。
出力：10_伸ばす数値.csv（重点分野の全変数と、条件ごとの判定）
"""
import numpy as np
import pandas as pd

from common import OUT, save

coef = pd.read_csv(OUT / "07_変数の係数.csv")
room = pd.read_csv(OUT / "09_改善余地.csv")
fe = pd.read_csv(OUT / "08_因果_係数.csv")
imp = pd.read_csv(OUT / "04_寄与度.csv")

d = room.merge(coef[["分野", "列名", "係数_1SD", "係数_1単位", "想定どおりの向きの割合", "効いた", "操作可能性", "操作可能性の理由"]],
               on=["分野", "列名"])
d["幸福度_主観スコア1点あたり"] = [imp.loc[(imp["対象"] == t) & (imp["分野"] == f), "係数_主観スコア1点あたり"].iloc[0]
                       for t, f in zip(d["類型"], d["分野"])]
d["条件1_主観スコアを説明できる"] = d["効いた"]
d["条件2_施策で動かせる"] = d["操作可能性"] != "困難"
d["条件3_伸びしろがある"] = d["伸びしろ"] > 0
fs = fe.groupby("列名").agg(想定どおり有意=("想定どおり有意", "any"), 逆向きに有意=("逆向きに有意", "any"),
                            逆向きの目的変数=("目的変数", lambda s: "・".join(s[fe.loc[s.index, "逆向きに有意"]])))
d["因果の確認"] = [("1時点のみ（確かめられない）" if c not in fs.index else
                  f"逆向きに有意（{fs.loc[c, '逆向きの目的変数']}）" if fs.loc[c, "逆向きに有意"] else
                  "想定どおりに有意" if fs.loc[c, "想定どおり有意"] else "判別できず") for c in d["列名"]]
d["条件4_年ごとの変化と食い違わない"] = ~d["因果の確認"].str.startswith("逆向き")
d["伸ばす数値"] = d["条件1_主観スコアを説明できる"] & d["条件2_施策で動かせる"] & d["条件3_伸びしろがある"] & d["条件4_年ごとの変化と食い違わない"]
d["主観スコアの上がり幅"] = np.where(d["伸ばす数値"], d["係数_1単位"].abs() * d["伸びしろ"], np.nan)
d["幸福度の上がり幅"] = d["主観スコアの上がり幅"] * d["幸福度_主観スコア1点あたり"]
# 主観スコアの不足：市の主観スコア（年代×性別の構成をそろえた値）と、同じ類型の平均との差。伸ばす数値でどれだけ埋まるかを見る
v = pd.read_csv(OUT / "03_市町村別_主観.csv")
for i, r in d.iterrows():
    s = v[f"主観_{r['分野']}"]
    d.loc[i, "主観スコア_市"] = s[(v["都道府県"] == "和歌山県") & (v["市区町村"] == r["市"])].iloc[0]
    d.loc[i, "主観スコア_類型平均"] = s[v["類型"] == r["類型"]].mean()
d["主観スコアの不足"] = d["主観スコア_類型平均"] - d["主観スコア_市"]
d["主観スコアの不足を埋める割合%"] = d["主観スコアの上がり幅"] / d["主観スコアの不足"] * 100


def reason(r):
    if r["伸ばす数値"]:
        return "伸ばす数値"
    out = []
    if not r["条件1_主観スコアを説明できる"]:
        out.append(f"主観スコアを説明できない（想定どおりの向き{r['想定どおりの向きの割合'] * 100:.0f}%）")
    if not r["条件2_施策で動かせる"]:
        out.append(f"施策で動かしにくい（{r['操作可能性の理由']}）")
    if not r["条件3_伸びしろがある"]:
        out.append(f"すでに類型の上位4分の1以上（類型内{r['類型内%']:.0f}%）")
    if not r["条件4_年ごとの変化と食い違わない"]:
        out.append(f"年ごとの変化と食い違う（{r['因果の確認']}）")
    return "・".join(out)


d["判定"] = d.apply(reason, axis=1)
d = d.sort_values(["市", "伸ばす数値", "幸福度の上がり幅", "想定どおりの向きの割合"], ascending=[True, False, False, False])
save(d, "10_伸ばす数値.csv")
print(d[["市", "分野", "表示名", "種別", "係数_1SD", "想定どおりの向きの割合", "操作可能性", "類型内%", "伸びしろ", "因果の確認", "主観スコアの上がり幅", "幸福度の上がり幅", "判定"]]
      .round(3).to_string(index=False))
